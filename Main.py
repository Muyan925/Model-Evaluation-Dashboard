# Gender and age groups
import pandas as pd
from scipy.stats import ttest_ind

# Get continuous variables (numeric type, excluding Gender and Age used for grouping)
numeric_cols = df_encoded.select_dtypes(include=['int64', 'float64']).columns
numeric_cols = [col for col in numeric_cols if col not in ['Gender', 'Age'] and isinstance(col, str)]

# Initialization results
t_results = []

# Gender grouping (Gender 0 vs 1)
for col in numeric_cols:
    group0 = df_encoded[df_encoded['Gender'] == 0][col].dropna()
    group1 = df_encoded[df_encoded['Gender'] == 1][col].dropna()
    if group0.nunique() <= 1 and group1.nunique() <= 1:
        continue
    t_stat, p_val = ttest_ind(group0, group1)
    t_results.append({
        'Feature': col,
        'Compared On': 'Gender',
        'p_value': round(float(p_val), 6),
        'Significant (p<0.05)': p_val < 0.05
    })

# Age groups (median Young vs Old)
median_age = df_encoded['Age'].median()
df_encoded['Age_Group'] = pd.cut(df_encoded['Age'], bins=[-1, median_age, float('inf')], labels=['Young', 'Old'])

for col in numeric_cols:
    group_young = df_encoded[df_encoded['Age_Group'] == 'Young'][col].dropna()
    group_old = df_encoded[df_encoded['Age_Group'] == 'Old'][col].dropna()
    if group_young.nunique() <= 1 and group_old.nunique() <= 1:
        continue
    t_stat, p_val = ttest_ind(group_young, group_old)
    t_results.append({
        'Feature': col,
        'Compared On': 'Age (group)',
        'p_value': round(float(p_val), 6),
        'Significant (p<0.05)': p_val < 0.05
    })

# Convert to DataFrame
t_test_df = pd.DataFrame(t_results)

# Conclusion format output
gender_sig = t_test_df[(t_test_df['Compared On'] == 'Gender') & (t_test_df['Significant (p<0.05)'])]
gender_nonsig = t_test_df[(t_test_df['Compared On'] == 'Gender') & (~t_test_df['Significant (p<0.05)'])]

age_sig = t_test_df[(t_test_df['Compared On'] == 'Age (group)') & (t_test_df['Significant (p<0.05)'])]
age_nonsig = t_test_df[(t_test_df['Compared On'] == 'Age (group)') & (~t_test_df['Significant (p<0.05)'])]

gender_sig_str = ", ".join(gender_sig['Feature'])
gender_nonsig_str = ", ".join(gender_nonsig['Feature'])
age_sig_str = ", ".join(age_sig['Feature'])
age_nonsig_str = ", ".join(age_nonsig['Feature'])

t_conclusion = (
    f"The gender difference in {gender_sig_str} is statistically significant, but the difference in {gender_nonsig_str} is not significant. "
    f"The difference in age is statistically significant in {age_sig_str}, but not in {age_nonsig_str}."
)

